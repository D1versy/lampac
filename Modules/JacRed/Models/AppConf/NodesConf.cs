namespace JacRed.Models.AppConf
{
    /// <summary>
    /// Узлы-помощники: вспомогательные машины, которые дают дому другой внешний IP для похода
    /// на трекеры. Узел объявляется сам (POST /qdl/nodes/hello) — в init.conf его прописывать
    /// НЕ нужно, это осознанное требование владельца: «нода сама стучится, а на сервере ничего
    /// настраивать не надо».
    ///
    /// Реализация — JacRed/Engine/NodeRegistry.cs, точка подключения — JacBaseController.HttpOrDirect.
    /// Сам узел живёт в отдельном репозитории E:\D1vision-node.
    /// </summary>
    public class NodesConf
    {
        /// <summary>
        /// Выключатель на случай «выключить всё и разбираться». false = реестр не принимает
        /// объявления и не выдаётся в выбор выхода, поведение дома ровно как до появления узлов.
        /// </summary>
        public bool enable = true;

        /// <summary>
        /// Сколько секунд помнить узел после последнего удара. Агент бьёт раз в 30с, так что
        /// 90 = три пропущенных удара. Клампится снизу до 30: TTL меньше периода удара выкидывал
        /// бы живой узел между ударами.
        /// </summary>
        public int ttlSeconds = 90;

        /// <summary>
        /// Предел размера реестра. Защита не от своих узлов, а от зациклившегося агента,
        /// который шлёт новое имя на каждый удар.
        /// </summary>
        public int maxNodes = 32;
    }
}
